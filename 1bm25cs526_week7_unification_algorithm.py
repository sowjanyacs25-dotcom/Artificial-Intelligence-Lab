def unify(x, y, substitution=None):
    if substitution is None:
        substitution = {}
    if x == y:
        return substitution
    elif isinstance(x, str) and x.islower():
        return unify_var(x, y, substitution)
    elif isinstance(y, str) and y.islower():
        return unify_var(y, x, substitution)
    elif isinstance(x, tuple) and isinstance(y, tuple):
        if len(x) != len(y):
            return None
        for a, b in zip(x, y):
            substitution = unify(a, b, substitution)
            if substitution is None:
                return None
        return substitution
    else:
        return None

def unify_var(var, x, substitution):
    if var in substitution:
        return unify(substitution[var], x, substitution)
    elif isinstance(x, str) and x in substitution:
        return unify(var, substitution[x], substitution)
    elif occurs_check(var, x, substitution):
        return None
    else:
        substitution[var] = x
        return substitution

def occurs_check(var, x, substitution):
    if var == x:
        return True
    if isinstance(x, str) and x in substitution:
        return occurs_check(var, substitution[x], substitution)
    if isinstance(x, tuple):
        return any(occurs_check(var, item, substitution) for item in x)
    return False

