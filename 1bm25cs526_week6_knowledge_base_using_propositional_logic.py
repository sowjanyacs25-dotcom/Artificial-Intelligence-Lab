from itertools import product


def implies(p, q):
    return (not p) or q


def iff(p, q):
    return p == q


def KB(model):
    P = model['P']
    Q = model['Q']
    return implies(P, Q) and P


def Query(model):
    return model['Q']


def TT_Entails(KB, Query, symbols):
    models = []

    for values in product([True, False], repeat=len(symbols)):
        model = dict(zip(symbols, values))

        kb_value = KB(model)
        query_value = Query(model)

        print("Model:", model,
              "| KB:", kb_value,
              "| Query:", query_value)

        if kb_value:
            models.append(model)

            if not query_value:
                return False, models

    return True, models


symbols = ['P', 'Q']

result, models = TT_Entails(KB, Query, symbols)

print("\nModels where KB is true:", models)

if result:
    print("KB entails the query.")
else:
    print("KB does NOT entail the query.")